// Assembles the exact Hamming matcher from its WAT sources with the pinned wabt development dependency and writes
//   packages/compute/src/matching/generated/exact-matching-wasm.ts   base64 modules, embedded so no Worker ever fetches a file
//   packages/compute/src/matching/generated/exact-matching-wasm.manifest.json   source, toolchain and output hashes
// Usage: node tools/build-wasm.ts [--check]
// --check assembles in memory and fails unless both checked-in files are byte-identical to a fresh build.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import wabtFactory from 'wabt';

const WABT_VERSION = '1.0.39';
const MATCHING_VERSION = 'hamming32-mutual-ratio075-max64/1';

const root = path.resolve(import.meta.dirname, '..');
const sourceDir = 'packages/compute/src/matching/wasm';
const generatedModule = 'packages/compute/src/matching/generated/exact-matching-wasm.ts';
const manifestFile = 'packages/compute/src/matching/generated/exact-matching-wasm.manifest.json';

interface Variant {
  readonly id: 'scalar' | 'simd';
  readonly source: string;
  readonly isSimd: boolean;
}
const VARIANTS: readonly Variant[] = [
  { id: 'scalar', source: 'hamming-exact-scalar.wat', isSimd: false },
  { id: 'simd', source: 'hamming-exact-simd.wat', isSimd: true },
];

interface Assembled extends Variant {
  readonly sourceSha256: string;
  readonly bytes: Buffer;
}

const sha256 = (data: string | Uint8Array): string =>
  createHash('sha256').update(data).digest('hex');

function fail(message: string): never {
  throw new Error(`build-wasm: ${message}`);
}

function checkToolchain(): void {
  const manifest = JSON.parse(
    readFileSync(path.join(root, 'node_modules/wabt/package.json'), 'utf8'),
  ) as {
    version: string;
  };
  if (manifest.version !== WABT_VERSION)
    fail(`expected wabt ${WABT_VERSION}, found ${manifest.version}`);
}

async function assemble(): Promise<Assembled[]> {
  const wabt = await wabtFactory();
  const assembled: Assembled[] = [];
  for (const variant of VARIANTS) {
    const text = readFileSync(path.join(root, sourceDir, variant.source), 'utf8');
    // Only SIMD (for the SIMD variant) is enabled; every other proposal stays off and no debug names are written.
    const module = wabt.parseWat(variant.source, text, {
      exceptions: false,
      mutable_globals: false,
      sat_float_to_int: false,
      sign_extension: false,
      simd: variant.isSimd,
      threads: false,
      function_references: false,
      multi_value: false,
      tail_call: false,
      bulk_memory: false,
      reference_types: false,
      annotations: false,
      code_metadata: false,
      gc: false,
      extended_const: false,
      relaxed_simd: false,
    });
    try {
      module.resolveNames();
      module.validate();
      const { buffer } = module.toBinary({
        log: false,
        canonicalize_lebs: true,
        relocatable: false,
        write_debug_names: false,
      });
      const bytes = Buffer.from(buffer);
      if (!WebAssembly.validate(bytes)) fail(`${variant.id} output does not validate`);
      assembled.push({ ...variant, sourceSha256: sha256(text), bytes });
    } finally {
      module.destroy();
    }
  }
  return assembled;
}

function renderModule(assembled: readonly Assembled[]): string {
  const entries = assembled.map((variant) =>
    [
      `  ${variant.id}: Object.freeze({`,
      `    source: '${variant.source}',`,
      `    byteLength: ${variant.bytes.length},`,
      `    sha256: '${sha256(variant.bytes)}',`,
      `    base64: '${variant.bytes.toString('base64')}',`,
      '  }),',
    ].join('\n'),
  );
  return [
    '/*! Copyright 2026 Andy',
    ' * SPDX-License-Identifier: Apache-2.0',
    ' */',
    '',
    `// Generated by tools/build-wasm.ts from ${sourceDir}/*.wat with wabt ${WABT_VERSION}; do not edit.`,
    '// WebAssembly modules (ABI 1) of the exact Hamming matcher, embedded as base64 so the single-file Worker never fetches a',
    '// .wasm file. They contain only the assembled original sources: no imports, no third-party code, no allocator.',
    '',
    'export const EXACT_MATCHING_WASM = Object.freeze({',
    '  abi: 1,',
    ...entries,
    '});',
    '',
  ].join('\n');
}

function renderManifest(assembled: readonly Assembled[], module: string): string {
  const manifest = {
    schema: 'livemira-exact-matching-wasm/1',
    matchingVersion: MATCHING_VERSION,
    abi: 1,
    buildScript: 'tools/build-wasm.ts',
    generatedModule,
    generatedModuleSha256: sha256(module),
    toolchain: {
      package: 'wabt',
      version: WABT_VERSION,
      role: 'WAT assembler (development dependency only)',
    },
    variants: assembled.map((variant) => ({
      id: variant.id,
      source: `${sourceDir}/${variant.source}`,
      sourceSha256: variant.sourceSha256,
      features: variant.isSimd ? ['simd'] : [],
      byteLength: variant.bytes.length,
      sha256: sha256(variant.bytes),
    })),
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

async function main(): Promise<void> {
  const isCheck = process.argv.slice(2).includes('--check');
  checkToolchain();
  const assembled = await assemble();
  const module = renderModule(assembled);
  const manifest = renderManifest(assembled, module);
  const outputs: [string, string][] = [
    [generatedModule, module],
    [manifestFile, manifest],
  ];
  if (isCheck) {
    const stale = outputs.filter(([file, text]) => {
      const full = path.join(root, file);
      return !existsSync(full) || readFileSync(full, 'utf8') !== text;
    });
    if (stale.length > 0)
      fail(`out of date: ${stale.map(([file]) => file).join(', ')}; run npm run build:wasm`);
  } else {
    for (const [file, text] of outputs) writeFileSync(path.join(root, file), text);
  }
  for (const variant of assembled) {
    console.log(`${variant.id}: ${variant.bytes.length} bytes, sha256 ${sha256(variant.bytes)}`);
  }
}

await main();
