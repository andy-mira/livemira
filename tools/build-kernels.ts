// Builds the Rust WASM kernels (kernels/vision, simd128) and embeds the binary as base64 in
// packages/features/src/generated/kernels-wasm.ts. `--check` rebuilds and verifies the embedded copy is current.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CRATE = join(ROOT, 'kernels', 'vision');
const OUT = join(ROOT, 'packages', 'features', 'src', 'generated', 'kernels-wasm.ts');

execFileSync('cargo', ['build', '--target', 'wasm32-unknown-unknown', '--release'], {
  cwd: CRATE,
  env: { ...process.env, RUSTFLAGS: '-C target-feature=+simd128' },
  stdio: 'inherit',
});
const wasm = readFileSync(join(CRATE, 'target', 'wasm32-unknown-unknown', 'release', 'livemira_kernels.wasm'));
const sha256 = createHash('sha256').update(wasm).digest('hex');
const text = `// Generated by tools/build-kernels.ts from kernels/vision. Do not edit.
export const KERNELS_WASM = Object.freeze({
  sha256: '${sha256}',
  byteLength: ${wasm.length},
  base64: '${wasm.toString('base64')}',
});
`;
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== text)
    throw new Error('Embedded kernels are stale; run node tools/build-kernels.ts');
  console.log(`kernels current (${wasm.length} bytes, ${sha256.slice(0, 12)})`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`kernels embedded (${wasm.length} bytes, ${sha256.slice(0, 12)})`);
}
