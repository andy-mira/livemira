// Assembles the exact Hamming matcher WAT sources into WebAssembly with the pinned wabt (toolchain-pin.json) and writes
//   packages/compute/src/exact-matching-wasm-binaries.mjs  (generated; base64 modules embedded so no Worker ever fetches a file)
//   packages/compute/exact-matching-wasm/manifest.json     (source, toolchain and output hashes)
// It never downloads anything. Obtain the pinned package once, outside the repository, e.g.
//   npm pack wabt@1.0.39 && tar -xzf wabt-1.0.39.tgz -C <dir>     (npm verifies the registry integrity on pack)
// then:
//   node packages/compute/exact-matching-wasm/build.mjs --wabt <dir>/package [--check]
// --check rebuilds in memory and fails unless the checked-in generated module and manifest are byte-identical.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const GENERATED = path.join(here, '../src/exact-matching-wasm-binaries.mjs'), MANIFEST = path.join(here, 'manifest.json');
const pin = JSON.parse(readFileSync(path.join(here, 'toolchain-pin.json'), 'utf8'));
const VARIANTS = [
  { id: 'scalar', source: 'hamming-exact-scalar.wat', features: {} },
  { id: 'simd', source: 'hamming-exact-simd.wat', features: { simd: true } },
];
const sha256 = data => createHash('sha256').update(data).digest('hex');
const fail = message => { console.error(`exact-matching-wasm build: ${message}`); process.exit(1); };

const args = process.argv.slice(2);
let wabtDir = null, check = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--check') check = true;
  else if (args[i] === '--wabt' && args[i + 1]) wabtDir = path.resolve(args[++i]);
  else fail(`unexpected argument ${args[i]}`);
}
if (!wabtDir) fail('--wabt <extracted wabt package directory> is required (see the header of this file)');
const wabtPackage = JSON.parse(readFileSync(path.join(wabtDir, 'package.json'), 'utf8'));
if (wabtPackage.name !== pin.package || wabtPackage.version !== pin.version) fail(`expected ${pin.package}@${pin.version}, found ${wabtPackage.name}@${wabtPackage.version}`);
const indexSha = sha256(readFileSync(path.join(wabtDir, 'index.js')));
if (indexSha !== pin.indexJsSha256) fail(`wabt index.js sha256 ${indexSha} differs from the pin`);
const wabt = await createRequire(path.join(wabtDir, 'package.json'))(wabtDir)();

const outputs = [];
for (const v of VARIANTS) {
  const text = readFileSync(path.join(here, v.source));
  // Only the listed proposal is enabled; every other wabt feature is off. No debug names are written.
  const features = { exceptions: false, mutable_globals: false, sat_float_to_int: false, sign_extension: false, simd: false, threads: false, function_references: false, multi_value: false, tail_call: false, bulk_memory: false, reference_types: false, annotations: false, code_metadata: false, gc: false, extended_const: false, relaxed_simd: false, ...v.features };
  const module = wabt.parseWat(v.source, text, features);
  try {
    module.resolveNames(); module.validate();
    const { buffer } = module.toBinary({ log: false, canonicalize_lebs: true, relocatable: false, write_debug_names: false });
    const bytes = Buffer.from(buffer);
    if (!WebAssembly.validate(bytes)) fail(`${v.id} output does not validate`);
    outputs.push({ ...v, sourceSha256: sha256(text), bytes });
  } finally { module.destroy(); }
}

const banner = `/*! Copyright 2026 Andy (@andy-mira)
 * SPDX-License-Identifier: Apache-2.0
 */
// GENERATED by packages/compute/exact-matching-wasm/build.mjs from the .wat sources in that directory with ${pin.package}@${pin.version}; do not edit.
// Base64 WebAssembly modules (ABI 1) of the exact Hamming matcher. They contain only the assembled original source: no imports, no
// third-party code, no allocator. Embedded as text so the single-file Blob Worker never fetches or imports a .wasm file.
`;
const entry = o => `  ${o.id}: Object.freeze({ source: '${o.source}', sourceSha256: '${o.sourceSha256}', bytes: ${o.bytes.length}, sha256: '${sha256(o.bytes)}',\n    base64: '${o.bytes.toString('base64')}' }),\n`;
const generated = `${banner}export const EXACT_MATCHING_WASM = Object.freeze({\n  abi: 1,\n${outputs.map(entry).join('')}});\n`;
const manifest = JSON.stringify({
  schema: 'lm-exact-matching-wasm/1',
  matchingVersion: 'hamming32-mutual-ratio075-max64/1', abi: 1,
  description: 'Exact BRIEF Hamming matcher assembled from original WAT sources (Apache-2.0). The WebAssembly contains no third-party code; wabt is the assembler only and is not redistributed.',
  buildScript: 'packages/compute/exact-matching-wasm/build.mjs', generatedModule: 'packages/compute/src/exact-matching-wasm-binaries.mjs', generatedModuleSha256: sha256(generated),
  toolchain: pin,
  variants: outputs.map(o => ({ id: o.id, source: `packages/compute/exact-matching-wasm/${o.source}`, sourceSha256: o.sourceSha256, features: Object.keys(o.features), bytes: o.bytes.length, sha256: sha256(o.bytes) })),
}, null, 2) + '\n';

if (check) {
  const same = (file, text) => existsSync(file) && readFileSync(file, 'utf8') === text;
  if (!same(GENERATED, generated) || !same(MANIFEST, manifest)) fail('checked-in generated module or manifest differs from a fresh build');
  console.log(JSON.stringify({ check: 'identical', variants: outputs.map(o => ({ id: o.id, bytes: o.bytes.length, sha256: sha256(o.bytes) })) }));
} else {
  writeFileSync(GENERATED, generated); writeFileSync(MANIFEST, manifest);
  console.log(JSON.stringify({ wrote: [path.relative(process.cwd(), GENERATED), path.relative(process.cwd(), MANIFEST)], variants: outputs.map(o => ({ id: o.id, bytes: o.bytes.length, sha256: sha256(o.bytes) })) }));
}
